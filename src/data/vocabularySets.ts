/**
 * 語彙セット。コースが「どの語の中から出題するか」を指す入れ物。
 *
 * いまは4つある。
 * - `common-practice`: ゲームの85語すべて。20コースがこれを参照する。
 * - `travel-practice`: 旅の場面の30語。海外旅行コースだけが参照する。
 * - `school-practice`: 学校の場面の30語。小学生・中学生の2コースが参照する。
 * - `hospitality-practice`: 接客・観光の場面の30語。接客・観光コースだけが参照する。
 *
 * セットは「どの場面のことばを出すか」で分けた、語の置き場所にすぎない。
 * 同じ語が複数のセットに入ることもある（旅と接客・観光は15語を共有する）。
 *
 * 語の確認状態（台帳）とは別の軸で、
 * あるセットに入っていない語が未確認というわけではない。
 * また、**学年別の難易度や、仕事で必要な力を表すものでもない**。
 * どの語がどの学年・どの職業に向くかを決められるデータは、まだ持っていない。
 */
export type VocabularySetId =
  | 'common-practice'
  | 'travel-practice'
  | 'school-practice'
  | 'hospitality-practice';

export interface VocabularySet {
  id: VocabularySetId;
  label: string;
  /**
   * このセットで使う語の固定ID。
   * 表示・管理上の順番であり、盤面への選出順ではない。
   * 盤面に出る語と並びは buildDeck が seed から決める。
   */
  pairIds: readonly number[];
}

